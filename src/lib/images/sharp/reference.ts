import { z } from 'zod'

import { sharpInputOptionsSchema } from './input-options.ts'
import {
  formatOptionsSchema,
  sharpJobSchema,
  sharpSettingsSchema,
  variantsSchema,
} from './job-schema.ts'
import { colourOpSchemas } from './ops-colour.ts'
import { filterOpSchemas } from './ops-filter.ts'
import { geometryOpSchemas } from './ops-geometry.ts'
import { outputOpSchemas } from './ops-output.ts'
import { OUTPUT_FORMATS } from './output-options.ts'
import { describeType } from './reference-types.ts'
import type { JsonSchema } from './reference-types.ts'

const HEADER = `# Sharp job reference

<!-- Generated by scripts/images/gen-sharp-reference.ts from the Zod schemas. Do not edit by hand. -->

Every field a \`pnpm images sharp\` job accepts, generated from the same schemas the CLI validates with. A field is optional unless marked required. Fields keep the names and meanings of [Sharp's API](https://sharp.pixelplumbing.com/api-constructor), so its documentation describes what each one does. The [CLI guide](cli.md#sharp-any-sharp-pipeline) explains how the pieces fit together; \`pnpm images schema sharp\` prints the same information as JSON Schema.`

const OP_GROUPS = [
  ['Geometry ops', geometryOpSchemas],
  ['Filter and tone ops', filterOpSchemas],
  ['Colour and channel ops', colourOpSchemas],
  ['Output, metadata and control ops', outputOpSchemas],
] as const

const FORMAT_NAMES: ReadonlySet<string> = new Set(OUTPUT_FORMATS)

/** Job fields documented in their own sections, summarised instead of spelled out in the job table. */
const JOB_FIELD_TYPES: Readonly<Record<string, string>> = {
  variants: 'object, see Variants',
  options: 'object, see Input options',
  ops: 'op[], see the op sections',
  formatOptions: 'object, see Format options',
  settings: 'object, see Settings',
}

function toJson(schema: z.ZodType): JsonSchema {
  return z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any' })
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function isSchema(value: unknown): value is JsonSchema {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function fieldRow(
  name: string,
  node: JsonSchema,
  required: boolean,
  type = describeType(node),
): string {
  const fallback =
    node.default === undefined ? '' : `\`${JSON.stringify(node.default)}\``
  const columns = [
    `\`${name}\``,
    type,
    required ? 'yes' : '',
    fallback,
    cell(node.description ?? ''),
  ]
  return `| ${columns.join(' | ')} |`
}

function nestedFields(node: JsonSchema): JsonSchema | undefined {
  if (node.type === 'object' && node.properties) return node
  if (node.type === 'array' && isSchema(node.items) && node.items.properties)
    return node.items
  return undefined
}

function collectRows(
  node: JsonSchema,
  prefix: string,
  rows: string[],
  skip: ReadonlySet<string>,
): void {
  const required = new Set(node.required ?? [])
  for (const [key, child] of Object.entries(node.properties ?? {})) {
    if (skip.has(key) || !isSchema(child)) continue
    const name = `${prefix}${key}`
    rows.push(fieldRow(name, child, required.has(key)))
    const nested = nestedFields(child)
    if (!nested) continue
    collectRows(
      nested,
      child.type === 'array' ? `${name}[].` : `${name}.`,
      rows,
      new Set(),
    )
  }
}

const TABLE_HEAD = [
  '| Field | Type | Required | Default | Description |',
  '| --- | --- | --- | --- | --- |',
]

function fieldTable(node: JsonSchema, skip: readonly string[] = []): string {
  const rows = [...TABLE_HEAD]
  collectRows(node, '', rows, new Set(skip))
  return rows.length === TABLE_HEAD.length ? 'No fields.' : rows.join('\n')
}

function jobTable(): string {
  const node = toJson(sharpJobSchema)
  const required = new Set(node.required ?? [])
  const rows = [...TABLE_HEAD]
  for (const [key, child] of Object.entries(node.properties ?? {})) {
    if (!isSchema(child)) continue
    rows.push(fieldRow(key, child, required.has(key), JOB_FIELD_TYPES[key]))
  }
  return rows.join('\n')
}

function opSection(schema: z.ZodType): string {
  const node = toJson(schema)
  const name = isSchema(node.properties?.op)
    ? String(node.properties.op.const)
    : ''
  const body = FORMAT_NAMES.has(name)
    ? `Takes the [\`${name}\` options](#${name}-options) as fields.`
    : fieldTable(node, ['op'])
  return `### \`${name}\`\n\n${body}`
}

function opsSections(): string[] {
  const sections: string[] = []
  for (const [title, schemas] of OP_GROUPS) {
    sections.push(`## ${title}`)
    for (const schema of schemas) sections.push(opSection(schema))
  }
  return sections
}

function formatSections(): string[] {
  const formats = toJson(formatOptionsSchema)
  const sections = [
    '## Format options (`formatOptions`, `--format-options`, format ops)',
    'The same fields are taken by `formatOptions.<format>` and by the format op of the same name.',
  ]
  for (const format of OUTPUT_FORMATS) {
    const node = formats.properties?.[format]
    if (isSchema(node))
      sections.push(`### \`${format}\` options`, fieldTable(node))
  }
  return sections
}

/** The Markdown reference of every sharp job field, op and option, before Prettier formatting. */
export function renderSharpReference(): string {
  const sections = [
    HEADER,
    '## Job',
    'The top level of a job, as passed with `--job`. The CLI flags map onto these fields.',
    jobTable(),
    '## Input options (`options`, `--options`)',
    'Passed to `sharp(input, options)`.',
    fieldTable(toJson(sharpInputOptionsSchema)),
    '## Variants (`variants`, `--widths`, `--manifest`)',
    fieldTable(toJson(variantsSchema)),
    '## Settings (`settings`, `--settings`)',
    fieldTable(toJson(sharpSettingsSchema)),
    ...formatSections(),
    ...opsSections(),
  ]
  return `${sections.join('\n\n')}\n`
}
